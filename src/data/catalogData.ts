  const cleanPin = pin.trim();
  if (PINCODE_REGISTRY[cleanPin]) {
    return PINCODE_REGISTRY[cleanPin];
  }
  if (cleanPin.length === 6 && /^\d+$/.test(cleanPin)) {
    // Standard serviceable tier for rest of India
    return {
      pincode: cleanPin,
      city: 'India Region',
      state: 'Standard Hub',
      serviceable: true,
      codAvailable: true,
      estimatedDays: 4,
      isExpressAvailable: false,
      deliveryCharge: 0,
    };
  }
  return {
    pincode: cleanPin,
    city: 'Unknown',
    state: '',
    serviceable: false,
    codAvailable: false,
    estimatedDays: 0,
    isExpressAvailable: false,
    deliveryCharge: 99,
  };
